-- 角色-权限矩阵（条件 JOIN：角色不存在时该行自然跳过，幂等）
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE (r.code = 'PLATFORM_ADMIN'
       AND p.code IN ('tenant:manage','user:manage','user:list','crm:use','inventory:use',
                      'finance:use','approval:use','legal:use','iot:monitor','iot:config'))
   OR (r.code = 'TENANT_ADMIN'
       AND p.code IN ('user:manage','user:list','crm:use','inventory:use','finance:use',
                      'approval:use','legal:use','iot:monitor','iot:config'))
   OR (r.code = 'USER'
       AND p.code IN ('user:list','crm:use','inventory:use','finance:use','approval:use',
                      'legal:use','iot:monitor'))
   OR (r.code = 'DUTY_OFFICER'
       AND p.code IN ('iot:monitor'));
